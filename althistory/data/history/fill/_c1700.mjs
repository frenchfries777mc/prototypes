/** 칠하기 목록에 쓰인 국가만 골라 polities를 만든다(템플릿 국가 ID는 제외). over: 이 템플릿 전용 덮어쓰기. */
export function pick(paint, templateIds, over = {}) {
  const out = {};
  for (const [id] of paint) {
    if (templateIds.includes(id) || out[id]) continue;
    const base = P[id];
    if (!base) throw new Error(`_c1700: 정의 없는 국가 ${id}`);
    out[id] = { ...base, ...(over[id] ?? {}) };
  }
  return out;
}

