export function build(Y, tpl) {
  const tplIds = new Set(Object.keys(tpl.polities));
  const alias = {};
  const defs = table(Y);
  const paint = rules(Y).map(([id, ...sels]) => [alias[id] ?? id, ...sels]);
  const used = new Set(paint.map((r) => r[0]));
  const polities = {};
  for (const id of used) {
    if (tplIds.has(id)) continue;
    const d = defs[id];
    if (!d) throw new Error(`[fill c1600] 정의되지 않은 국가 ${id}`);
    const [n, e, s, a, c] = d;
    polities[id] = { n, e, s, a, ...(c ? { c } : {}) };
  }
  return { polities, paint };
}
